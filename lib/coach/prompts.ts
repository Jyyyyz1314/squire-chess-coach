export function coachTask(mode: CoachMode) {
  if (mode === 'training') return `这是开局陪练的逐步反馈。课程已给出预期着、学员实际着法、变例主题与当前局面；不要另猜一条开局线。输出 220–420 个中文字符，严格使用以下五段：
【本步结论】明确说明学员是否命中课程着法，并写出预期着。
【这步在做什么】从中心、发展、王安全、兵形、空间、线路或节奏中选择真正相关的要点，解释预期着的具体作用。
【为什么不是刚才那步】若学员走错，公平说明实际着可能的想法，再指出它与本课目标的差异；没有引擎对比分数时不得断言它必败或损失兵值。
【后续计划】结合变例主题说明接下来双方各自应争取什么，只给一条短而合法的示意变化。
【记忆钩子】用一句易记规则帮助下次识别同类局面。`;
  if (mode === 'question') return `这是棋手针对当前棋盘提出的问题。先识别问题属于候选着比较、开局辨识、战略计划、战术计算还是规则解释，然后直截了当地回答。
严格使用以下三段，输出 180–380 个中文字符：
【直接回答】先在 1–2 句话内回答用户真正问的内容，不回避结论。
【局面依据】结合 FEN、当前行棋方、开局信息和引擎候选线说明原因；必要时给出一条最多 4–6 个半回合的变化。
【实战建议】告诉棋手在相似局面中应检查什么。
若用户询问的候选着不在已提供引擎线中：
- 明确写出“现有候选线没有直接评估这步”，不要把“未入前三”等同于错误；
- 若它是可靠的开局选择或合理候选，先说明“可以走”，再比较它与首选的风格和计划；
- 不得伪造精确分数、强制变化、棋子受阻或兵形弱点；不确定的事实不要猜；
- 只有专项引擎比较才能回答精确优劣，证据不足时明确说明这一限制。`;
  if (mode === 'deep') return `这是深入讲解。输出 250–450 个中文字符，严格使用以下四段：
【局面判断】当前阶段、双方计划和最重要的局面特征。
【为什么】当前走法或最佳候选着的目的，以及关键因果。
【如果这样走】用自然语言解释一条关键变化，最多展示 4–6 个半回合。
【带走一条】总结一条能在相似局面中复用的判断原则。`;
  return `这是快速点评。只输出 60–120 个中文字符，严格使用以下两段：
【结论】当前最佳选择及它是否符合局面需要。
【关键】这步的主要目的与最需要防范的一个风险。`;
}
